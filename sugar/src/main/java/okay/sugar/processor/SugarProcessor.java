package okay.sugar.processor;

import java.io.IOException;
import java.io.Writer;
import java.util.ArrayDeque;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.stream.Collectors;
import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.RoundEnvironment;
import javax.annotation.processing.SupportedAnnotationTypes;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.AnnotationMirror;
import javax.lang.model.element.AnnotationValue;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.ExecutableElement;
import javax.lang.model.element.Modifier;
import javax.lang.model.element.RecordComponentElement;
import javax.lang.model.element.TypeElement;
import javax.lang.model.element.TypeParameterElement;
import javax.lang.model.element.VariableElement;
import javax.lang.model.type.DeclaredType;
import javax.lang.model.type.PrimitiveType;
import javax.lang.model.type.TypeKind;
import javax.lang.model.type.TypeMirror;
import javax.tools.Diagnostic;

/** THE SUGAR: it only generates. {@code @Effect} on a plain interface gives the effect as okay.rows has it
 * ({@code NameOp}); {@code @Uses} on a class gives the operations of its row, each at its place ({@code NameOps}).
 * What is generated is ordinary okay.rows source: nothing here is needed at run time. */
@SupportedAnnotationTypes({SugarProcessor.EFFECT, SugarProcessor.USES})
public final class SugarProcessor extends AbstractProcessor {
  static final String EFFECT = "okay.sugar.Effect";
  static final String USES = "okay.sugar.Uses";
  static final String OP = "okay.effect.Op";

  /** one operation: how it is called, its record, the type of its answer */
  record Operation(String name, String record, String typeParams, String answer, boolean isVoid, List<Param> params) {
    String declared() { return params.stream().map(p -> p.type + " " + p.name).collect(Collectors.joining(", ")); }
    String passed() { return params.stream().map(Param::name).collect(Collectors.joining(", ")); }
  }

  record Param(String type, String name) {}

  /** an effect of a row: its type in the row, and the program that asks one of its operations */
  record Fx(String type, List<Operation> operations, java.util.function.Function<Operation, String> asks) {}

  @Override
  public SourceVersion getSupportedSourceVersion() { return SourceVersion.latestSupported(); }

  @Override
  public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment round) {
    for (TypeElement annotation : annotations) {
      boolean effect = annotation.getQualifiedName().contentEquals(EFFECT);
      for (Element e : round.getElementsAnnotatedWith(annotation)) {
        try {
          if (effect) effect((TypeElement) e); else uses((TypeElement) e);
        } catch (Refused r) {
          processingEnv.getMessager().printMessage(Diagnostic.Kind.ERROR, r.getMessage(), r.at);
        }
      }
    }
    return true;
  }

  static final class Refused extends RuntimeException {
    final transient Element at;
    Refused(Element at, String message) {
      super(message);
      this.at = at;
    }
  }

  // ---- @Effect: a plain interface -> NameOp, the effect as data

  private void effect(TypeElement type) {
    List<Operation> operations = methods(type);
    String name = type.getSimpleName() + "Op";
    String access = type.getModifiers().contains(Modifier.PUBLIC) ? "public " : "";
    String it = type.getQualifiedName().toString();
    StringBuilder s = new StringBuilder();
    s.append("package ").append(packageOf(type)).append(";\n\n");
    s.append("import okay.effect.Eff;\nimport okay.effect.Operation;\nimport okay.rows.Comp;\n");
    s.append("import okay.rows.Effects;\n\n");
    s.append("/** The effect {@link ").append(it).append("} as data, generated by okay.sugar: an operation is a\n");
    s.append(" * record, {@code name(..)} the program that asks it, {@code handledBy} the handler an implementation\n");
    s.append(" * of the interface is. */\n");
    s.append("@javax.annotation.processing.Generated(\"okay.sugar\")\n");
    s.append(access).append("sealed interface ").append(name).append("<T> extends Operation<T, ").append(name);
    s.append("<?>> {\n");
    for (Operation o : operations) {
      s.append("  record ").append(o.record).append("(").append(o.declared()).append(") implements ").append(name);
      s.append("<").append(o.answer).append("> {}\n");
    }
    for (Operation o : operations) {
      s.append("\n  static Comp<").append(o.answer).append(", Eff<").append(name).append("<?>, ?>> ");
      s.append(o.name).append("(").append(o.declared()).append(") {\n");
      s.append("    return Effects.perform(new ").append(o.record).append("(").append(o.passed()).append("));\n  }\n");
    }
    s.append("\n  /** the handler an implementation is: each operation answered in place by its method */\n");
    s.append("  static <A, R> Comp<A, R> handledBy(").append(it).append(" impl, Comp<A, ? super Eff<").append(name);
    s.append("<?>, R>> body) {\n");
    s.append("    return Effects.answering(op -> switch (op) {\n");
    for (Operation o : operations) {
      String call = "impl." + o.name + "(" + o.params.stream().map(p -> "o." + p.name + "()")
          .collect(Collectors.joining(", ")) + ")";
      s.append("      case ").append(o.record).append(" o -> ");
      if (o.isVoid) s.append("{\n        ").append(call).append(";\n        yield o.answer(null);\n      }\n");
      else s.append("o.answer(").append(call).append(");\n");
    }
    s.append("    }, body);\n  }\n}\n");
    write(packageOf(type) + "." + name, s, type);
  }

  /** the operations of a plain interface: its abstract methods */
  private List<Operation> methods(TypeElement type) {
    if (type.getKind() != ElementKind.INTERFACE) throw new Refused(type, "@Effect goes on an interface");
    if (!type.getTypeParameters().isEmpty()) {
      throw new Refused(type, "@Effect: an interface with type parameters is not supported; write the effect by "
          + "hand, its records naming their answers (docs/start.md, \"The other forms\")");
    }
    List<Operation> out = new ArrayList<>();
    Set<String> names = new HashSet<>();
    for (Element e : type.getEnclosedElements()) {
      if (e.getKind() != ElementKind.METHOD) continue;
      if (e.getModifiers().contains(Modifier.STATIC) || e.getModifiers().contains(Modifier.DEFAULT)) continue;
      ExecutableElement m = (ExecutableElement) e;
      String name = m.getSimpleName().toString();
      if (!m.getTypeParameters().isEmpty()) {
        throw new Refused(m, "@Effect: a generic method cannot be an operation: its answer's type would not be "
            + "known to the record");
      }
      if (!m.getThrownTypes().isEmpty()) {
        throw new Refused(m, "@Effect: an operation declares no exceptions; a failure is an effect of its own");
      }
      if (!names.add(name)) throw new Refused(m, "@Effect: two operations named " + name + "; give each a name");
      TypeMirror r = m.getReturnType();
      boolean isVoid = r.getKind() == TypeKind.VOID;
      out.add(new Operation(name, capitalized(name), "", isVoid ? "java.lang.Void" : boxed(r), isVoid,
          params(m.getParameters())));
    }
    if (out.isEmpty()) throw new Refused(type, "@Effect: the interface has no operations");
    return out;
  }

  // ---- @Uses: a class's row -> NameOps, every operation at its place

  private void uses(TypeElement type) {
    List<Fx> row = new ArrayList<>();
    for (TypeElement effect : listed(type)) row.add(fx(type, effect));
    String rowType = "?";
    for (int i = row.size() - 1; i >= 0; i--) rowType = "Eff<" + row.get(i).type + ", " + rowType + ">";
    String name = type.getSimpleName() + "Ops";
    String access = type.getModifiers().contains(Modifier.PUBLIC) ? "public " : "";
    StringBuilder s = new StringBuilder();
    s.append("package ").append(packageOf(type)).append(";\n\n");
    s.append("import okay.effect.Eff;\nimport okay.rows.Comp;\nimport okay.rows.Effects;\n\n");
    s.append("/** The operations of the row of {@link ").append(type.getQualifiedName()).append("}, generated by\n");
    s.append(" * okay.sugar: each at its place, all of one type of row,\n * {@code ").append(rowType).append("}. */\n");
    s.append("@javax.annotation.processing.Generated(\"okay.sugar\")\n");
    s.append(access).append("final class ").append(name).append(" {\n  private ").append(name).append("() {}\n");
    Map<String, String> seen = new LinkedHashMap<>();
    for (int place = 0; place < row.size(); place++) {
      Fx fx = row.get(place);
      for (Operation o : fx.operations) {
        String signature = o.name + "(" + o.params.stream().map(Param::type).collect(Collectors.joining(",")) + ")";
        String other = seen.put(signature, fx.type);
        if (other != null) {
          throw new Refused(type, "@Uses: " + signature + " is an operation of both " + other + " and " + fx.type
              + "; ask one of them by hand, with up(perform(..))");
        }
        String asked = fx.asks.apply(o);
        for (int i = 0; i < place; i++) asked = "Effects.up(" + asked + ")";
        s.append("\n  ").append(access).append("static ").append(o.typeParams.isEmpty() ? "" : o.typeParams + " ");
        s.append("Comp<").append(o.answer).append(", ").append(rowType).append("> ").append(o.name).append("(");
        s.append(o.declared()).append(") {\n    return Effects.fit(").append(asked).append(");\n  }\n");
      }
    }
    s.append("}\n");
    write(packageOf(type) + "." + name, s, type);
  }

  /** the classes a {@code @Uses} lists, in their order */
  private List<TypeElement> listed(TypeElement type) {
    for (AnnotationMirror a : type.getAnnotationMirrors()) {
      if (!((TypeElement) a.getAnnotationType().asElement()).getQualifiedName().contentEquals(USES)) continue;
      for (AnnotationValue v : a.getElementValues().values()) {
        List<TypeElement> out = new ArrayList<>();
        for (Object each : (List<?>) v.getValue()) {
          Object value = ((AnnotationValue) each).getValue();
          if (!(value instanceof DeclaredType d)) throw new Refused(type, "@Uses: not an effect: " + value);
          out.add((TypeElement) d.asElement());
        }
        if (out.isEmpty()) break;
        return out;
      }
    }
    throw new Refused(type, "@Uses lists no effect");
  }

  private Fx fx(TypeElement user, TypeElement effect) {
    boolean plain = effect.getAnnotationMirrors().stream().anyMatch(a ->
        ((TypeElement) a.getAnnotationType().asElement()).getQualifiedName().contentEquals(EFFECT));
    if (plain) {
      String op = packageOf(effect) + "." + effect.getSimpleName() + "Op";
      return new Fx(op + "<?>", methods(effect), o -> op + "." + o.name + "(" + o.passed() + ")");
    }
    List<Operation> operations = records(user, effect);
    int n = effect.getTypeParameters().size();
    String type = effect.getQualifiedName() + (n == 0 ? "" : "<" + "?, ".repeat(n - 1) + "?>");
    return new Fx(type, operations, o -> "Effects.perform(new " + o.record + (o.typeParams.isEmpty() ? "" : "<>")
        + "(" + o.passed() + "))");
  }

  /** the operations of an effect written by hand: the records among its subtypes */
  private List<Operation> records(TypeElement user, TypeElement effect) {
    List<TypeElement> found = new ArrayList<>();
    for (Element e : effect.getEnclosedElements()) if (e.getKind() == ElementKind.RECORD) found.add((TypeElement) e);
    for (TypeMirror permitted : effect.getPermittedSubclasses()) {
      TypeElement p = (TypeElement) processingEnv.getTypeUtils().asElement(permitted);
      if (p.getKind() == ElementKind.RECORD && !found.contains(p)) found.add(p);
    }
    List<Operation> out = new ArrayList<>();
    for (TypeElement record : found) {
      TypeMirror answer = answerOf(record.asType());
      if (answer == null) continue;
      String typeParams = record.getTypeParameters().isEmpty() ? "" : "<" + record.getTypeParameters().stream()
          .map(this::declared).collect(Collectors.joining(", ")) + ">";
      List<? extends RecordComponentElement> components = record.getRecordComponents();
      List<Param> params = new ArrayList<>();
      for (RecordComponentElement c : components) params.add(new Param(c.asType().toString(), "" + c.getSimpleName()));
      String simple = record.getSimpleName().toString();
      out.add(new Operation(Character.toLowerCase(simple.charAt(0)) + simple.substring(1),
          record.getQualifiedName().toString(), typeParams, answer.toString(), false, params));
    }
    if (out.isEmpty()) {
      throw new Refused(user, "@Uses: " + effect.getQualifiedName() + " is neither an interface marked @Effect nor "
          + "an effect whose operations are records (okay.effect.Op)");
    }
    return out;
  }

  /** the answer's type of an operation: the X of the {@code Op<E, X, Self>} among its supertypes */
  private TypeMirror answerOf(TypeMirror operation) {
    ArrayDeque<TypeMirror> queue = new ArrayDeque<>(List.of(operation));
    Set<String> visited = new HashSet<>();
    while (!queue.isEmpty()) {
      TypeMirror t = queue.poll();
      if (!visited.add(t.toString())) continue;
      if (t instanceof DeclaredType d && ((TypeElement) d.asElement()).getQualifiedName().contentEquals(OP)
          && d.getTypeArguments().size() == 3) {
        return d.getTypeArguments().get(1);
      }
      queue.addAll(processingEnv.getTypeUtils().directSupertypes(t));
    }
    return null;
  }

  // ---- words

  private String declared(TypeParameterElement p) {
    String bounds = p.getBounds().stream().map(TypeMirror::toString).filter(b -> !b.equals("java.lang.Object"))
        .collect(Collectors.joining(" & "));
    return p.getSimpleName() + (bounds.isEmpty() ? "" : " extends " + bounds);
  }

  private List<Param> params(List<? extends VariableElement> parameters) {
    List<Param> out = new ArrayList<>();
    for (VariableElement p : parameters) out.add(new Param(p.asType().toString(), p.getSimpleName().toString()));
    return out;
  }

  private String boxed(TypeMirror t) {
    return t.getKind().isPrimitive()
        ? processingEnv.getTypeUtils().boxedClass((PrimitiveType) t).getQualifiedName().toString() : t.toString();
  }

  private String packageOf(TypeElement type) {
    return processingEnv.getElementUtils().getPackageOf(type).getQualifiedName().toString();
  }

  private static String capitalized(String name) {
    return Character.toUpperCase(name.charAt(0)) + name.substring(1);
  }

  private void write(String name, CharSequence source, TypeElement from) {
    try (Writer w = processingEnv.getFiler().createSourceFile(name, from).openWriter()) {
      w.append(source);
    } catch (IOException e) {
      throw new Refused(from, "okay.sugar could not write " + name + ": " + e.getMessage());
    }
  }
}
